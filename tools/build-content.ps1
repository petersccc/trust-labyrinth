# build-content.ps1
# Regenerates every text file of the page from Katarina's sources:
#   content/trust-labyrinth-content.json  -> content.js
#   content/privacy-notice-{de,en,zh}.md  -> privacy-content.js (overlay)
#                                          + privacy-notice.html (standalone)
# If the source folder exists (default: ../trust labyrinth/trust-labyrinth
# next to this project), its JSON and Markdown files are copied into
# content/ first, so content/ always holds what the page was built from.
#
# Run:  pwsh -File tools/build-content.ps1 ["<source folder>"]
param(
  [string]$Source = (Join-Path $PSScriptRoot "..\..\trust labyrinth\trust-labyrinth")
)
$ErrorActionPreference = "Stop"
$app = Split-Path -Parent $PSScriptRoot
$content = Join-Path $app "content"
$utf8 = New-Object Text.UTF8Encoding $false
$files = @("trust-labyrinth-content.json", "privacy-notice-de.md", "privacy-notice-en.md", "privacy-notice-zh.md")

New-Item -ItemType Directory -Force $content | Out-Null
if (Test-Path $Source) {
  foreach ($f in $files) { Copy-Item (Join-Path $Source $f) (Join-Path $content $f) -Force }
  Write-Host "Copied sources from $Source"
}

# ---- content.js -------------------------------------------------------
$jsonText = [IO.File]::ReadAllText((Join-Path $content "trust-labyrinth-content.json"), [Text.Encoding]::UTF8)
$null = $jsonText | ConvertFrom-Json   # fails loudly if the JSON is broken
$header = @"
// content.js
// GENERATED by tools/build-content.ps1 from content/trust-labyrinth-content.json
// (Katarina's copy file). Do not edit by hand: change the JSON and re-run
// the script, so every visible text stays word for word.
const CONTENT =
"@
[IO.File]::WriteAllText((Join-Path $app "content.js"), $header + $jsonText.Trim() + ";`n", $utf8)

# ---- privacy notice ---------------------------------------------------
function Esc($s) { $s.Replace('&', '&amp;').Replace('<', '&lt;').Replace('>', '&gt;') }
function Inline($s) {
  $s = Esc $s
  $s = [regex]::Replace($s, '\*\*(.+?)\*\*', '<strong>$1</strong>')
  $s = [regex]::Replace($s, '[\w.+-]+@[\w-]+\.[\w.]+', { param($m) "<a href=""mailto:$($m.Value)"">$($m.Value)</a>" })
  return $s
}
function Convert-Md($path) {
  $lines = [IO.File]::ReadAllLines($path, [Text.Encoding]::UTF8)
  $out = New-Object System.Text.StringBuilder
  $para = New-Object System.Collections.Generic.List[string]
  $inList = $false
  $flush = {
    if ($para.Count) { [void]$out.AppendLine("<p>" + ($para -join "<br>") + "</p>"); $para.Clear() }
  }
  foreach ($l in $lines) {
    if ($l.Trim() -eq '') {
      & $flush
      if ($inList) { [void]$out.AppendLine("</ul>"); $inList = $false }
      continue
    }
    if ($l -match '^#{1,3}\s+(.*)$') {
      & $flush
      if ($inList) { [void]$out.AppendLine("</ul>"); $inList = $false }
      [void]$out.AppendLine("<h2>" + (Inline $Matches[1]) + "</h2>")
      continue
    }
    if ($l -match '^\s*[-*]\s+(.*)$') {
      & $flush
      if (-not $inList) { [void]$out.AppendLine("<ul>"); $inList = $true }
      [void]$out.AppendLine("<li>" + (Inline $Matches[1].TrimEnd()) + "</li>")
      continue
    }
    $para.Add((Inline $l.TrimEnd()))
  }
  & $flush
  if ($inList) { [void]$out.AppendLine("</ul>") }
  return $out.ToString()
}

$json = $jsonText | ConvertFrom-Json
$titles = ($json.fixed_elements_on_every_page | Where-Object element -eq 'Footer link')
$notice = @{}
foreach ($lang in 'de', 'en', 'zh') {
  $notice[$lang] = "<h1>" + (Esc $titles.$lang) + "</h1>`n" + (Convert-Md (Join-Path $content "privacy-notice-$lang.md"))
}

# privacy-content.js, used by the overlay in app.js
$js = "// privacy-content.js`n// GENERATED by tools/build-content.ps1 from content/privacy-notice-{de,en,zh}.md.`n// Do not edit by hand.`nconst PRIVACY_HTML = {`n"
foreach ($lang in 'de', 'en', 'zh') {
  $js += "  ${lang}: " + ($notice[$lang] | ConvertTo-Json) + ",`n"
}
$js += "};`n"
[IO.File]::WriteAllText((Join-Path $app "privacy-content.js"), $js, $utf8)

